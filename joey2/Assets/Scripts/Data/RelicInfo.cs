public class RelicInfo
{
	public int id;
	public string cardImage;
	public string name;
	public string description;

	public RelicInfo()
	{
	}

	public RelicInfo(int id, string cardImage, string name, string description)
	{
		this.id = id;
		this.cardImage = cardImage;
		this.name = name;
		this.description = description;
	}
}

