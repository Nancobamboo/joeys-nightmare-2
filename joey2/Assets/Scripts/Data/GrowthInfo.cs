public class GrowthInfo
{
	public int id;
	public string name;
	public int depend;
	public string desc;
	public int price;

	public GrowthInfo(int id, string name, int depend, string desc, int price)
	{
		this.id = id;
		this.name = name;
		this.depend = depend;
		this.desc = desc;
		this.price = price;
	}
}

